export type BodyPartId = (typeof records)[number]['id'];
export type DamageDef = 'Blunt' | 'Poke' | 'Cut' | 'Stab' | 'Bite' | 'Bullet' | 'Arrow';
export interface BodyPart {
  id: BodyPartId;
  name: string;
  index: number;
  parent: BodyPartId | null;
  children: readonly BodyPartId[];
  defName: string;
  height: 'Top' | 'Middle' | 'Bottom';
  depth: 'Inside' | 'Outside';
  coverage: number;
  coverageWithChildren: number;
  weight: number;
  hitPoints: number;
  bleedRate: number;
  skinCovered: boolean;
  solid: boolean;
  conceptual: boolean;
  destroyableByDamage: boolean;
  tags: readonly string[];
  groups: readonly string[];
  hitChanceFactors: Readonly<Partial<Record<DamageDef, number>>>;
}
export const BODY_PART_LIST: readonly BodyPart[] = records;
export const BODY_PARTS = Object.freeze(
  Object.fromEntries(records.map((p) => [p.id, p])),
) as unknown as Readonly<Record<BodyPartId, BodyPart>>;

/** Minimal structural view avoids a runtime dependency on the injury module. */
export interface BodyState {
  wounds: readonly { part: BodyPartId; severity: number }[];
  missingParts: readonly { part: BodyPartId }[];
}
export const DAMAGE_DEFS: readonly DamageDef[] = [
  'Blunt',
  'Poke',
  'Cut',
  'Stab',
  'Bite',
  'Bullet',
  'Arrow',
];
const clamp = (n: number) => Math.max(0, Math.min(1, n));
export function validBodyPart(value: unknown): value is BodyPartId {
  return typeof value === 'string' && Object.hasOwn(BODY_PARTS, value);
}
function requirePart(part: BodyPartId): BodyPart {
  if (!validBodyPart(part)) throw new RangeError('身体部位无效');
  return BODY_PARTS[part];
}
/** Unity Mathf.RoundToInt rounds exact halves to even, unlike Math.round. */
export function roundToEven(value: number): number {
  const low = Math.floor(value),
    fraction = value - low;
  return fraction === 0.5 ? low + (low % 2) : Math.round(value);
}
export function roundedCapacity(value: number): number {
  return roundToEven(Math.max(0, value) * 100) / 100;
}
export function isDescendantOrSelf(part: BodyPartId, ancestor: BodyPartId): boolean {
  requirePart(part);
  requirePart(ancestor);
  for (let current: BodyPartId | null = part; current; current = BODY_PARTS[current].parent)
    if (current === ancestor) return true;
  return false;
}
export function missingAncestor(state: BodyState, part: BodyPartId): BodyPartId | null {
  requirePart(part);
  return state.missingParts.find((m) => isDescendantOrSelf(part, m.part))?.part ?? null;
}
export function isPartMissing(state: BodyState, part: BodyPartId): boolean {
  return missingAncestor(state, part) !== null;
}
export function partHealth(state: BodyState, part: BodyPartId): number {
  const definition = requirePart(part);
  if (isPartMissing(state, part)) return 0;
  const damage = state.wounds.reduce((sum, w) => sum + (w.part === part ? w.severity : 0), 0);
  return roundToEven(
    Math.max(definition.destroyableByDamage ? 0 : 1, definition.hitPoints - damage),
  );
}
export function partEfficiency(state: BodyState, part: BodyPartId): number {
  const definition = requirePart(part),
    fraction = partHealth(state, part) / definition.hitPoints;
  // Outside non-core parts use the native 10%..100% efficiency range.
  return definition.depth === 'Outside' && part !== 'torso'
    ? clamp((fraction - 0.1) / 0.9)
    : fraction;
}
export function damageHitWeight(part: BodyPartId, damageDef: DamageDef): number {
  const definition = requirePart(part);
  if (!DAMAGE_DEFS.includes(damageDef)) throw new RangeError('伤害类型无效');
  return definition.weight * (definition.hitChanceFactors[damageDef] ?? 1);
}
export function chooseHitPart(
  state: BodyState,
  damageDef: DamageDef,
  roll: number,
  depth: 'Outside' | 'Inside' | 'Any' = 'Outside',
  height: 'Top' | 'Middle' | 'Bottom' | 'Any' = 'Any',
): BodyPartId | null {
  if (
    !Number.isFinite(roll) ||
    roll < 0 ||
    roll >= 1 ||
    !DAMAGE_DEFS.includes(damageDef) ||
    !['Outside', 'Inside', 'Any'].includes(depth) ||
    !['Top', 'Middle', 'Bottom', 'Any'].includes(height)
  )
    throw new RangeError('命中采样参数无效');
  const depthCandidates = BODY_PART_LIST.filter(
    (p) => (depth === 'Any' || p.depth === depth) && !isPartMissing(state, p.id) && p.weight > 0,
  );
  let candidates = depthCandidates.filter((p) => height === 'Any' || p.height === height);
  if (!candidates.length) candidates = depthCandidates;
  const useFactors = candidates.some((p) => damageHitWeight(p.id, damageDef) > 0);
  const weight = (p: BodyPart) => (useFactors ? damageHitWeight(p.id, damageDef) : p.weight);
  let threshold = candidates.reduce((n, p) => n + weight(p), 0) * roll;
  for (const p of candidates) {
    threshold -= weight(p);
    if (threshold < 0) return p.id;
  }
  return candidates.at(-1)?.id ?? null;
}
export type CapacityKey =
  | 'consciousness'
  | 'moving'
  | 'manipulation'
  | 'sight'
  | 'breathing'
  | 'bloodPumping'
  | 'bloodFiltration'
  | 'metabolism'
  | 'hearing'
  | 'talking'
  | 'eating';
export type CapacityReasons = Record<CapacityKey, string[]>;
const tagged = (tag: string) => BODY_PART_LIST.filter((p) => p.tags.includes(tag));
const average = (values: number[]) =>
  values.length ? values.reduce((a, b) => a + b, 0) / values.length : 1;
function partReason(state: BodyState, part: BodyPartId): string {
  const missing = missingAncestor(state, part);
  if (missing)
    return `${BODY_PARTS[missing].name}缺失${BODY_PARTS[missing].children.length ? '（下属部位均不可用）' : ''}`;
  return `${BODY_PARTS[part].name} ${partHealth(state, part)}/${BODY_PARTS[part].hitPoints}，功能 ${Math.round(partEfficiency(state, part) * 100)}%`;
}
function reasonsFor(state: BodyState, parts: readonly BodyPart[]): string[] {
  return [
    ...new Set(
      parts.filter((p) => partEfficiency(state, p.id) !== 1).map((p) => partReason(state, p.id)),
    ),
  ];
}
export function tagEfficiency(state: BodyState, tag: string, bestWeight = -1): number {
  const efficiencies = tagged(tag).map((p) => partEfficiency(state, p.id));
  if (efficiencies.length < 2 || bestWeight < 0) return average(efficiencies);
  const best = Math.max(...efficiencies);
  return (
    best * bestWeight +
    ((efficiencies.reduce((a, b) => a + b, 0) - best) / (efficiencies.length - 1)) *
      (1 - bestWeight)
  );
}
/** Native natural-tool groups average remaining records; missing records are excluded here. */
export function naturalGroupEfficiency(state: BodyState, group: string): number {
  const present = BODY_PART_LIST.filter(
    (p) => p.groups.includes(group) && !isPartMissing(state, p.id),
  );
  return present.length ? average(present.map((p) => partEfficiency(state, p.id))) : 0;
}
function limbParts(core: BodyPart, segmentTag: string, digitTag: string) {
  let connectedRoot = core;
  while (connectedRoot.parent && BODY_PARTS[connectedRoot.parent].tags.includes(segmentTag))
    connectedRoot = BODY_PARTS[connectedRoot.parent];
  return {
    segments: tagged(segmentTag).filter((p) => isDescendantOrSelf(p.id, connectedRoot.id)),
    digits: tagged(digitTag).filter((p) => isDescendantOrSelf(p.id, core.id)),
  };
}
export function limbEfficiency(state: BodyState, kind: 'Manipulation' | 'Moving') {
  const weight = kind === 'Manipulation' ? 0.8 : 0.4;
  const limbs = tagged(`${kind}LimbCore`).map((core) => {
    const { segments, digits } = limbParts(core, `${kind}LimbSegment`, `${kind}LimbDigit`);
    const base = [core, ...segments].reduce((n, p) => n * partEfficiency(state, p.id), 1);
    return {
      part: core.id,
      efficiency:
        base * (1 - weight + weight * average(digits.map((p) => partEfficiency(state, p.id)))),
      reasons: reasonsFor(state, [core, ...segments, ...digits]),
    };
  });
  return {
    efficiency: limbs.length ? average(limbs.map((l) => l.efficiency)) : 0,
    functionalPercentage: limbs.length
      ? limbs.filter((l) => l.efficiency > 0).length / limbs.length
      : 0,
    reasons: [...new Set(limbs.flatMap((l) => l.reasons))],
    limbs,
  };
}
/** Native part/organ factors. Consciousness and condition modifiers compose in survival.ts. */
const bodyCache = new WeakMap<
  BodyState,
  { key: string; value: ReturnType<typeof calculateBodyFunctions> }
>();
export function bodyFunctions(state: BodyState) {
  // Age, tending and blood change independently of part HP; avoid rebuilding the
  // 64-node dependency tree every simulation tick. The value key also notices
  // direct edits made by save loading/tests instead of relying on mutation hooks.
  const key =
    state.wounds.map((w) => `${w.part}:${w.severity}`).join(',') +
    '|' +
    state.missingParts.map((m) => m.part).join(',');
  const cached = bodyCache.get(state);
  if (cached?.key === key) return cached.value;
  const value = calculateBodyFunctions(state);
  bodyCache.set(state, { key, value });
  return value;
}
function calculateBodyFunctions(state: BodyState) {
  const tagsReasons = (...tags: string[]) => reasonsFor(state, tags.flatMap(tagged));
  const bloodPumping = roundedCapacity(tagEfficiency(state, 'BloodPumpingSource'));
  const breathing = roundedCapacity(
    tagEfficiency(state, 'BreathingSource') *
      Math.min(1, tagEfficiency(state, 'BreathingPathway')) *
      Math.min(1, tagEfficiency(state, 'BreathingSourceCage')),
  );
  const bloodFiltration = roundedCapacity(
    tagEfficiency(state, 'BloodFiltrationKidney') * tagEfficiency(state, 'BloodFiltrationLiver'),
  );
  const manipulation = limbEfficiency(state, 'Manipulation'),
    moving = limbEfficiency(state, 'Moving');
  const movingFactor =
    (moving.functionalPercentage < 0.4999 ? 0 : moving.efficiency) *
    tagEfficiency(state, 'Pelvis') *
    tagEfficiency(state, 'Spine') *
    (0.8 + 0.2 * breathing) *
    (0.8 + 0.2 * bloodPumping);
  const capacityReasons: CapacityReasons = {
    consciousness: tagsReasons('ConsciousnessSource'),
    moving: [...moving.reasons, ...tagsReasons('Pelvis', 'Spine')],
    manipulation: manipulation.reasons,
    sight: tagsReasons('SightSource'),
    bloodPumping: tagsReasons('BloodPumpingSource'),
    breathing: tagsReasons('BreathingSource', 'BreathingPathway', 'BreathingSourceCage'),
    bloodFiltration: tagsReasons('BloodFiltrationKidney', 'BloodFiltrationLiver'),
    metabolism: tagsReasons('MetabolismSource'),
    hearing: tagsReasons('HearingSource'),
    talking: tagsReasons('TalkingSource', 'TalkingPathway', 'Tongue'),
    eating: tagsReasons('EatingSource', 'EatingPathway', 'Tongue'),
  };
  return {
    bloodPumping,
    breathing,
    bloodFiltration,
    sight: roundedCapacity(tagEfficiency(state, 'SightSource', 0.75)),
    metabolism: roundedCapacity(tagEfficiency(state, 'MetabolismSource')),
    hearing: roundedCapacity(tagEfficiency(state, 'HearingSource', 0.75)),
    talkingFactor:
      tagEfficiency(state, 'TalkingSource') *
      Math.min(1, tagEfficiency(state, 'TalkingPathway')) *
      Math.min(1, tagEfficiency(state, 'Tongue')),
    eatingFactor:
      tagEfficiency(state, 'EatingSource') *
      Math.min(1, tagEfficiency(state, 'EatingPathway')) *
      (0.5 + 0.5 * tagEfficiency(state, 'Tongue')),
    consciousnessSource: tagEfficiency(state, 'ConsciousnessSource'),
    movingFactor,
    manipulationFactor: manipulation.efficiency,
    capacityReasons,
  };
}
